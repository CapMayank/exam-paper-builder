// LIVE model run (sends text to Gemini). Generates two sections of an English Class 10 paper from the
// official-pattern template and checks structure. Run against a COPY of the database:
//   DATABASE_URL=file:/path/copy.db npx next start -p 3100   (GEMINI_API_KEY from .env)
//   node scripts/e2e-live-generation.mjs http://localhost:3100 /path/en10.json
import { readFileSync } from "node:fs";

const base = process.argv[2] ?? "http://localhost:3100";
const tpl = JSON.parse(readFileSync(process.argv[3], "utf8"));
let cookie = "";
let failures = 0;

async function call(method, path, json, { auth = true } = {}) {
  const res = await fetch(base + path, {
    method,
    headers: { ...(json ? { "Content-Type": "application/json" } : {}), ...(auth && cookie ? { cookie } : {}) },
    body: json ? JSON.stringify(json) : undefined,
  });
  const sc = res.headers.get("set-cookie");
  if (sc) cookie = sc.split(";")[0];
  const data = await res.json().catch(() => null);
  return { status: res.status, data };
}
function check(name, cond, extra = "") {
  if (!cond) failures++;
  console.log(`${cond ? "PASS" : "FAIL"}  ${name}${cond ? "" : "  -> " + String(extra).slice(0, 400)}`);
}

let r = await call("POST", "/api/auth/login", { email: "teacher@school.edu", password: "password123" }, { auth: false });
check("login with seed account", r.status === 200);

const book = (await call("POST", "/api/books", { title: "First Flight", subject: "English", className: "Class 10" })).data;
const chapters = [];
for (const [n, t] of [[1, "A Letter to God"], [2, "Nelson Mandela: Long Walk to Freedom"], [3, "Two Stories about Flying"]]) {
  chapters.push((await call("POST", `/api/books/${book.id}/chapters`, { number: n, title: t })).data);
}
const perChapter = [25, 25, 25];
r = await call("POST", "/api/blueprints", {
  name: "English 10 live",
  bookId: book.id,
  examType: "ANNUAL",
  durationMin: 180,
  academicSession: "2026-27",
  componentsJson: JSON.stringify(tpl.components),
  chapters: chapters.map((c, i) => ({ chapterId: c.id, marks: perChapter[i] })),
  sections: tpl.sections,
});
check("blueprint from official-pattern template saves", r.status === 200 || r.status === 201, JSON.stringify(r.data));
const bp = r.data;
const paper = (await call("POST", "/api/papers", { title: "English live", blueprintId: bp.id, layout: "PAGE", schoolName: "Test School" })).data;

const plan = (await call("GET", `/api/papers/${paper.id}/ai-plan`)).data?.plan;
check("plan has a passage section with 2 slots", plan?.sections?.some((s) => s.sectionType === "UNSEEN_PASSAGE" && s.slots.length === 2), JSON.stringify(plan?.sections?.map((s) => [s.sectionTitle, s.slots?.length])));

async function runSection(sec) {
  const gen = await call("POST", `/api/papers/${paper.id}/ai-generate-section`, {
    sectionId: sec.sectionId, sectionTitle: sec.sectionTitle, sectionType: sec.sectionType,
    sectionInstructions: sec.sectionInstructions, marksEach: sec.marksEach, language: "en",
    difficulty: "BALANCED", model: "gemini-flash-lite-latest", generateDiagrams: false, slots: sec.slots,
  });
  console.log(`  generate ${sec.sectionTitle}: status=${gen.status} isMock=${gen.data?.isMock} n=${gen.data?.questions?.length}`);
  if (gen.status !== 200) return { gen };
  const commit = await call("POST", `/api/papers/${paper.id}/ai-commit-section`, {
    sectionId: sec.sectionId, questions: gen.data.questions, isMock: gen.data.isMock,
  });
  console.log(`  commit: status=${commit.status} ${commit.status === 200 ? "added=" + commit.data.addedCount + " templateFallback=" + commit.data.templateFallbackCount : JSON.stringify(commit.data).slice(0, 600)}`);
  return { gen, commit };
}

const passageSec = plan.sections.find((s) => s.sectionType === "UNSEEN_PASSAGE");
const out = await runSection(passageSec);
check("passage section generated by the model (not offline template)", out.gen?.status === 200 && out.gen.data.isMock === false, JSON.stringify(out.gen?.data).slice(0, 300));
check("passage section committed", out.commit?.status === 200, JSON.stringify(out.commit?.data).slice(0, 400));

const view = (await call("GET", `/api/papers/${paper.id}`)).data;
const passages = view.items.filter((i) => i.sectionId === passageSec.sectionId);
check("two passages placed in the passage section", passages.length === 2, passages.length);
for (const [i, it] of passages.entries()) {
  const q = it.question;
  const sp = q.subparts ?? [];
  const marks = sp.reduce((a, s) => a + (s.marks || 0), 0);
  check(`passage ${i + 1}: UNSEEN_PASSAGE with a real passage (>= 80 words)`, q.type === "UNSEEN_PASSAGE" && q.text.trim().split(/\s+/).length >= 80, `${q.type} words=${q.text.trim().split(/\s+/).length}`);
  check(`passage ${i + 1}: 5 sub-questions worth 5 marks`, sp.length === 5 && marks === 5, `sp=${sp.length} marks=${marks}`);
  check(`passage ${i + 1}: every sub-question is an MCQ with 4 options and an answer`, sp.every((s) => (s.options?.length ?? 0) === 4 && (s.answer || "").trim()), JSON.stringify(sp.map((s) => [s.options?.length, !!s.answer])));
  console.log(`  --- passage ${i + 1} preview: ${q.text.trim().slice(0, 160).replace(/\s+/g, " ")}...`);
  console.log(`      Q(i): ${sp[0]?.text?.slice(0, 120)}`);
}

const grammarSec = plan.sections.find((s) => s.sectionType === "FILL_BLANK");
if (grammarSec) {
  const g = await runSection(grammarSec);
  check("grammar fill-in-the-blank section generated and committed", g.commit?.status === 200, JSON.stringify(g.gen?.data ?? g.commit?.data).slice(0, 400));
}

const after = (await call("GET", `/api/papers/${paper.id}`)).data;
console.log("  implications:", after.implications.map((i) => `${i.code}:${i.message.slice(0, 70)}`).join(" | "));
const aud = await call("POST", "/api/ai/audit-paper", { paperId: paper.id });
console.log(`  audit: status=${aud.data?.data?.status} aiStage=${aud.data?.data?.aiStage} findings=${aud.data?.data?.findings?.length}`);
check("audit's independent model review actually ran", aud.data?.data?.aiStage === "COMPLETED", aud.data?.data?.aiStage);
for (const f of (aud.data?.data?.findings ?? []).slice(0, 6)) console.log(`   [${f.severity}] ${f.type}: ${String(f.issue).slice(0, 140)}`);

console.log(failures === 0 ? "\nALL PASSED" : `\n${failures} FAILED`);
process.exit(failures === 0 ? 0 : 1);
